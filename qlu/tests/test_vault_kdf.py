    def test_private_binary_request_has_exact_framing_and_accepts_maximum(self):
        import hashlib
        command = self.fixture("import hashlib\nrequest = sys.stdin.buffer.read(1041)\nsys.stdout.buffer.write(hashlib.sha256(request).digest())\n")
        phrase = b"p" * 1024
        with patch.object(kdf, "_worker_command", return_value=command):
            self.assertEqual(kdf.derive(phrase, SALT), hashlib.sha256(SALT + phrase).digest())

    def test_stalled_children_are_killed_reaped_and_never_retried(self):
        cases = {
            "never reads": "time.sleep(60)\n",
            "hangs after input": "sys.stdin.buffer.read()\ntime.sleep(60)\n",
            "32 bytes then hangs": "sys.stdin.buffer.read()\nos.write(1, b'x' * 32)\ntime.sleep(60)\n",
            "closes stdout then hangs": "sys.stdin.buffer.read()\nos.close(1)\ntime.sleep(60)\n",
        }
        for label, source in cases.items():
            command = self.fixture(source)
            started = time.monotonic()
            with self.subTest(label=label), patch.object(kdf, "_worker_command", return_value=command), \
                    patch.object(kdf, "DERIVATION_TIMEOUT_SECONDS", 0.25), \
                    patch.object(kdf.subprocess, "Popen", side_effect=self.capture_spawn) as spawn:
                with self.assertRaisesRegex(kdf.DerivationError, "^Password derivation failed$"):
                    kdf.derive(PHRASE, SALT)
                self.assertEqual(spawn.call_count, 1)
                self.assertLess(time.monotonic() - started, 2)
            self.assert_reaped()
            self.assert_next_derivation_works()

    def test_bad_lengths_status_crash_and_flood_fail_without_exposing_output(self):
        sources = [
            "sys.stdin.buffer.read()\nos.write(1, b'x' * %d)\n" % size for size in (0, 1, 31, 33)
        ] + [
            "sys.stdin.buffer.read()\nos.write(1, b'x' * 32)\nsys.exit(7)\n",
            "sys.stdin.buffer.read()\nos.kill(os.getpid(), 9)\n",
            "sys.stdin.buffer.read()\nwhile True: os.write(1, b'x' * 8192)\n",
            "sys.stdin.buffer.read()\nos.write(2, b'PRIVATE BACKEND DETAIL' * 8192)\nsys.exit(1)\n",
        ]
        for index, source in enumerate(sources):
            stdout, stderr = io.StringIO(), io.StringIO()
            command = self.fixture(source)
            with self.subTest(case=index), patch.object(kdf, "_worker_command", return_value=command), \
                    patch.object(kdf, "DERIVATION_TIMEOUT_SECONDS", 1), \
                    patch.object(kdf.subprocess, "Popen", side_effect=self.capture_spawn), \
                    redirect_stdout(stdout), redirect_stderr(stderr):
                with self.assertRaisesRegex(kdf.DerivationError, "^Password derivation failed$"):
                    kdf.derive(PHRASE, SALT)
            self.assertEqual(stdout.getvalue() + stderr.getvalue(), "")
            self.assert_reaped()
            self.assert_next_derivation_works()

    def test_invalid_requests_and_timeout_configuration_never_spawn(self):
        inputs = [(b"", SALT), (b"x" * 1025, SALT), ("secret", SALT),
                  (bytearray(b"secret"), SALT), (PHRASE, b"x" * 15),
                  (PHRASE, b"x" * 17), (PHRASE, bytearray(SALT))]
        with patch.object(kdf.subprocess, "Popen") as spawn:
            for phrase, salt in inputs:
                with self.subTest(length=repr(type(phrase))), self.assertRaises(kdf.DerivationError):
                    kdf.derive(phrase, salt)
            for timeout in (0, -1, float("nan"), float("inf"), True, "15"):
                with self.subTest(timeout=timeout), patch.object(kdf, "DERIVATION_TIMEOUT_SECONDS", timeout):
                    with self.assertRaises(kdf.DerivationError):
                        kdf.derive(PHRASE, SALT)
            spawn.assert_not_called()

    def test_queue_wait_times_out_without_spawning(self):
        self.assertTrue(kdf.shared.ARGON2_LOCK.acquire(timeout=1))
        try:
            with patch.object(kdf, "DERIVATION_TIMEOUT_SECONDS", 0.05), \
                    patch.object(kdf.subprocess, "Popen") as spawn:
                with self.assertRaises(kdf.DerivationError):
                    kdf.derive(PHRASE, SALT)
                spawn.assert_not_called()
        finally:
            kdf.shared.ARGON2_LOCK.release()
        self.assert_next_derivation_works()

    def test_queue_time_is_subtracted_from_child_deadline(self):
        # A controlled clock proves budget accounting without assuming prompt
        # thread scheduling on a busy hosted runner. Other tests use real hangs.
        clock = [100.0]
        gate = Mock()
        def acquire(*, timeout):
            self.assertAlmostEqual(timeout, 0.3)
            clock[0] += 0.15
            return True
        gate.acquire.side_effect = acquire
        def worker(phrase, salt, deadline):
            self.assertEqual((phrase, salt), (PHRASE, SALT))
            self.assertAlmostEqual(deadline, 100.3)
            self.assertAlmostEqual(kdf._remaining(deadline), 0.15)
            return EXPECTED
        with patch.object(kdf, "DERIVATION_TIMEOUT_SECONDS", 0.3), \
                patch.object(kdf.time, "monotonic", side_effect=lambda: clock[0]), \
                patch.object(kdf.shared, "ARGON2_LOCK", gate), \
                patch.object(kdf, "_run_worker", side_effect=worker):
            self.assertEqual(kdf.derive(PHRASE, SALT), EXPECTED)
        gate.acquire.assert_called_once()
        gate.release.assert_called_once_with()

    def test_interrupt_after_spawn_reaps_helper_and_releases_gate(self):
        command = self.fixture("time.sleep(60)\n")
        with patch.object(kdf, "_worker_command", return_value=command), \
                patch.object(kdf.subprocess, "Popen", side_effect=self.capture_spawn), \
                patch.object(kdf.selectors.DefaultSelector, "select", side_effect=KeyboardInterrupt):
            with self.assertRaises(KeyboardInterrupt):
                kdf.derive(PHRASE, SALT)
        self.assert_reaped()
        self.assert_next_derivation_works()

    def test_unreapable_child_is_quarantined_until_exit_observed(self):
        child = Mock()
        child.poll.return_value = None
        child.wait.side_effect = subprocess.TimeoutExpired("unreapable public fixture", 1)
        try:
            self.assertFalse(kdf._cleanup(child))
            self.assertIs(kdf.shared.QUARANTINED_CHILD, child)
            with patch.object(kdf.subprocess, "Popen") as spawn:
                with self.assertRaises(kdf.DerivationError):
                    kdf.derive(PHRASE, SALT)
                spawn.assert_not_called()
            child.poll.return_value = 0
            self.assertEqual(kdf.derive(PHRASE, SALT), EXPECTED)
            self.assertIsNone(kdf.shared.QUARANTINED_CHILD)
        finally:
            kdf.shared.QUARANTINED_CHILD = None

    def test_spawn_failure_has_fixed_error_and_releases_gate(self):
        with patch.object(kdf.subprocess, "Popen", side_effect=OSError(PHRASE.decode())):
            with self.assertRaisesRegex(kdf.DerivationError, "^Password derivation failed$"):
                kdf.derive(PHRASE, SALT)
        self.assert_next_derivation_works()

    def test_successful_exit_observed_after_deadline_is_rejected(self):
        offset = [0.0]
        monotonic = time.monotonic
        def spawn(*args, **kwargs):
            child = self.capture_spawn(*args, **kwargs)
            wait = child.wait
            def delayed_wait(*, timeout):
                result = wait(timeout=timeout)
                offset[0] = 30.0
                return result
            child.wait = delayed_wait
            return child
        with patch.object(kdf.subprocess, "Popen", side_effect=spawn), \
                patch.object(kdf.time, "monotonic", side_effect=lambda: monotonic() + offset[0]):
            with self.assertRaises(kdf.DerivationError):
                kdf.derive(PHRASE, SALT)
        self.assert_reaped()
        self.assert_next_derivation_works()

    def test_interrupted_cleanup_keeps_child_quarantined(self):
        child = Mock()
        child.poll.return_value = None
        child.wait.side_effect = KeyboardInterrupt
        try:
            with self.assertRaises(KeyboardInterrupt):
                kdf._cleanup(child)
            self.assertIs(kdf.shared.QUARANTINED_CHILD, child)
            with patch.object(kdf.subprocess, "Popen") as spawn:
                with self.assertRaises(kdf.DerivationError):
                    kdf.derive(PHRASE, SALT)
                spawn.assert_not_called()
            child.poll.return_value = 0
            self.assertEqual(kdf.derive(PHRASE, SALT), EXPECTED)
        finally:
            kdf.shared.QUARANTINED_CHILD = None

    def test_actual_worker_rejects_bad_input_with_no_output_or_traceback(self):
        for request in (b"", b"x" * 16, b"x" * 1041, b"x" * 4096):
            with self.subTest(length=len(request)):
                result = subprocess.run(kdf._worker_command(), input=request, capture_output=True, timeout=3)
                self.assertEqual(result.returncode, 1)
                self.assertEqual(result.stdout + result.stderr, b"")

    def test_worker_suppresses_native_construction_and_derivation_failures(self):
        for fail_during in ("construction", "derivation"):
            class FailingNative:
                def __init__(self, **kwargs):
                    if fail_during == "construction":
                        raise UnsupportedAlgorithm("private provider detail")

                def derive(self, phrase):
                    raise UnsupportedAlgorithm("private provider detail")

            output, error = io.BytesIO(), io.StringIO()
            with self.subTest(fail_during=fail_during), \
                    patch.object(vault_kdf_worker.sys, "stdin", SimpleNamespace(buffer=io.BytesIO(SALT + PHRASE))), \
                    patch.object(vault_kdf_worker.sys, "stdout", SimpleNamespace(buffer=output)), \
                    patch.object(vault_kdf_worker.sys, "stderr", error), \
                    patch("cryptography.hazmat.primitives.kdf.argon2.Argon2id", FailingNative):
                self.assertEqual(vault_kdf_worker.main(), 1)
            self.assertEqual(output.getvalue(), b"")
            self.assertEqual(error.getvalue(), "")


