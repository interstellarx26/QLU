import subprocess
import sys
import tempfile
import time
import unittest
from unittest.mock import Mock, patch
from types import SimpleNamespace

from cryptography.exceptions import UnsupportedAlgorithm

from qlu import vault
from qlu import vault_kdf_worker


kdf = vault.vault_kdf
PHRASE = b"QLU public derivation vector v1"
SALT = bytes(range(16))
EXPECTED = bytes.fromhex("35c57890ea5bf58fedf05dfeffd7361c9bd5830f5e20b5f81a797bee18cc1cc3")


class VaultKDFTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name).resolve()
        self.children = []
        self.real_popen = subprocess.Popen

    def tearDown(self):
        for child in self.children:
            if child.poll() is None:
                child.kill()
            child.wait(timeout=2)
        self.temporary.cleanup()

    def fixture(self, source):
        path = self.root / "public_helper_fixture.py"
        path.write_text("import os, sys, time\n" + source)
        return [sys.executable, "-I", str(path)]

    def capture_spawn(self, *args, **kwargs):
        child = self.real_popen(*args, **kwargs)
        self.children.append(child)
        return child

    def assert_reaped(self):
        self.assertTrue(self.children)
        for child in self.children:
            self.assertIsNotNone(child.returncode)
            # wait() must already have collected it, rather than leaving a zombie.
            with self.assertRaises(ChildProcessError):
                os.waitpid(child.pid, os.WNOHANG)

    def assert_next_derivation_works(self):
        self.assertIsNone(kdf.shared.QUARANTINED_CHILD)
        self.assertEqual(kdf.derive(PHRASE, SALT), EXPECTED)

    def test_real_isolated_helper_matches_independent_legacy_vector(self):
        command = kdf._worker_command()
        self.assertEqual(command[:2], [sys.executable, "-I"])
        self.assertTrue(Path(command[2]).is_absolute())
        with patch.object(kdf.subprocess, "Popen", side_effect=self.capture_spawn) as spawn:
            self.assertEqual(kdf.derive(PHRASE, SALT), EXPECTED)
        self.assertEqual(spawn.call_count, 1)
        self.assertNotIn(PHRASE.decode(), repr(spawn.call_args))
        self.assertNotIn("env", spawn.call_args.kwargs)
        self.assertEqual(spawn.call_args.kwargs["stderr"], subprocess.DEVNULL)
        self.assert_reaped()

