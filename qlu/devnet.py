#!/usr/bin/env python3
"""Local-only, explicitly Bitcoin-regtest foundation for QLU development.

This is not a QLU consensus implementation. Test coins have no monetary value.
Only this controller's processes may be stopped; existing data is never erased.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import socket
import subprocess
import sys
import time
import uuid


PROJECT = Path(__file__).resolve().parent.parent
UPSTREAM_COMMIT = "9be056a8a72b624dae9623b2f7bded92c2a21c91"
NODE_COUNT = 4
P2P_BASE = 19440
RPC_BASE = 19540
WALLET = "qlu-smoke"


class DevnetError(RuntimeError):
    """A failed safety check or node operation."""


class RpcError(DevnetError):
    def __init__(self, message: str, code: int | None = None):
        super().__init__(message)
        self.code = code


def secure_directory(path: Path) -> None:
    """Create a private directory, refusing symlinks and non-directories."""
    if path.is_symlink() or (path.exists() and not path.is_dir()):
        raise DevnetError(f"Unsafe directory: {path}")
    path.mkdir(mode=0o700, exist_ok=True)
    path.chmod(0o700)


def reject_symlinks(path: Path) -> None:
    if path.is_symlink():
        raise DevnetError(f"Symlinks are not allowed in devnet data: {path}")
    for base, dirs, files in os.walk(path, followlinks=False):
        for name in dirs + files:
            entry = Path(base) / name
            if entry.is_symlink():
                raise DevnetError(f"Symlinks are not allowed in devnet data: {entry}")
            if entry.is_file() and entry.stat().st_nlink != 1:
                raise DevnetError(f"Hard links are not allowed in devnet data: {entry}")


def write_private(path: Path, text: str) -> None:
    if path.is_symlink():
        raise DevnetError(f"Refusing symlink: {path}")
    temporary = path.with_name(path.name + "." + uuid.uuid4().hex + ".tmp")
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def configuration(index: int, chain: str = "regtest", p2p_base: int = P2P_BASE, rpc_base: int = RPC_BASE) -> str:
    if index not in range(NODE_COUNT):
        raise DevnetError("Node index must be 0 through 3")
    lines = [
        ("# Generated by qlu/devnet.py. Local Bitcoin regtest; no real funds." if chain == "regtest" else f"# Generated by qlu/devnet.py. Local {chain}; no real funds."),
        f"{chain}=1", "server=1", "daemon=0", "listen=1", "discover=0",
        "dns=0", "dnsseed=0", "fixedseeds=0", "forcednsseed=0",
        "listenonion=0", "onion=0", "i2pacceptincoming=0", "natpmp=0",
        "privatebroadcast=0", "onlynet=ipv4", "dbcache=64", "maxmempool=50",
        # Upstream reserves 8 full-relay, 2 block-relay and 1 feeler slots.
        # Sixteen leaves five inbound slots, enough for the three other nodes.
        "maxconnections=16", "fallbackfee=0.0002", "persistmempool=1",
        f"[{chain}]", f"port={p2p_base + index}",
        f"bind=127.0.0.1:{p2p_base + index}",
        f"rpcport={rpc_base + index}", f"rpcbind=127.0.0.1:{rpc_base + index}",
        "rpcallowip=127.0.0.1",
    ]
    if chain == "qludev":
        lines.insert(1, "disablewallet=1")
    lines.extend(f"connect=127.0.0.1:{p2p_base + peer}"
                 for peer in range(NODE_COUNT) if peer != index)
    return "\n".join(lines) + "\n"


class Devnet:
    chain = "regtest"
    p2p_base = P2P_BASE
    rpc_base = RPC_BASE
    data_name = "devnet"
    process_label = "QLUFoundation"

    def __init__(self, root: Path = PROJECT):
        self.root = root.resolve()
        self.local = self.root / ".local"
        self.data = self.local / self.data_name
        self.state_file = self.data / "controller.json"
        self.binary = self.root / "build/qlu-foundation/bin/bitcoind"
        self.cli = self.root / "build/qlu-foundation/bin/bitcoin-cli"

    def node(self, index: int) -> Path:
        if index not in range(NODE_COUNT):
            raise DevnetError("Node index must be 0 through 3")
        return self.data / f"node{index}"

    def setup(self) -> None:
        secure_directory(self.local)
        secure_directory(self.data)
        reject_symlinks(self.data)
        for index in range(NODE_COUNT):
            node = self.node(index)
            secure_directory(node)
            conf = node / "bitcoin.conf"
            expected = configuration(index, self.chain, self.p2p_base, self.rpc_base)
            if conf.exists() and conf.read_text(encoding="utf-8") != expected:
                raise DevnetError(f"Configuration changed; refusing to overwrite or run: {conf}")
            if not conf.exists():
                write_private(conf, expected)
            conf.chmod(0o600)

    def require_binaries(self) -> None:
        for binary in (self.binary, self.cli):
            if not binary.is_file() or not os.access(binary, os.X_OK):
                raise DevnetError(f"Build the pinned foundation first; missing executable: {binary}")
            if not binary.resolve().is_relative_to(self.root / "build"):
                raise DevnetError(f"Executable escapes the project build directory: {binary}")

    def read_state(self) -> dict:
        if not self.state_file.exists():
            return {}
        if self.state_file.is_symlink():
            raise DevnetError("Controller state must not be a symlink")
        try:
            state = json.loads(self.state_file.read_text(encoding="utf-8"))
            if not isinstance(state, dict):
                raise ValueError("not an object")
            for key, entry in state.items():
                if key not in {str(i) for i in range(NODE_COUNT)}:
                    raise ValueError("invalid node")
                if (not isinstance(entry, dict) or type(entry.get("pid")) is not int
                        or entry["pid"] <= 1
                        or re.fullmatch(r"[a-f0-9]{32}", str(entry.get("token", ""))) is None):
                    raise ValueError("invalid ownership record")
            return state
        except (ValueError, TypeError) as error:
            raise DevnetError("Invalid controller ownership state; refusing process actions") from error

    def save_state(self, state: dict) -> None:
        write_private(self.state_file, json.dumps(state, indent=2) + "\n")

    @staticmethod
    def pid_command(pid: int) -> str:
        result = subprocess.run(["ps", "-ww", "-p", str(pid), "-o", "stat=", "-o", "command="],
                                text=True, capture_output=True, check=False)
        fields = result.stdout.strip().split(None, 1)
        # A direct child may be a zombie until Python reaps it. It has exited
        # and must not be mistaken for a live, unrelated reused PID.
        return fields[1] if result.returncode == 0 and len(fields) == 2 and "Z" not in fields[0] else ""

    def owned(self, index: int, entry: dict) -> bool:
        command = self.pid_command(entry["pid"])
        # PID reuse is not sufficient: require the executable, exact datadir and
        # an unpredictable marker unique to this launch before any signal/RPC stop.
        return (command.startswith(str(self.binary) + " ")
                and f" -datadir={self.node(index)} " in command + " "
                and f" -uacomment={self.process_label}-{entry['token']} " in command + " ")

    def rpc(self, index: int, method: str, *params, wallet: bool = False):
        command = [str(self.cli), f"-{self.chain}", f"-datadir={self.node(index)}",
                   f"-conf={self.node(index) / 'bitcoin.conf'}",
                   "-rpcconnect=127.0.0.1", f"-rpcport={self.rpc_base + index}",
                   "-rpcclienttimeout=10", "-stdin"]
        if wallet:
            command.append(f"-rpcwallet={WALLET}")
        command.append(method)
        values = [value if isinstance(value, str) else json.dumps(value) for value in params]
        if any("\n" in value or "\r" in value for value in values):
            raise DevnetError("RPC arguments must not contain newlines")
        try:
            result = subprocess.run(command, input="\n".join(values) + ("\n" if values else ""),
                                    capture_output=True, text=True, timeout=15, check=False)
        except subprocess.TimeoutExpired as error:
            raise RpcError(f"Node {index} RPC timed out") from error
        if result.returncode:
            match = re.search(r"error code:\s*(-?\d+)", result.stderr)
            raise RpcError(f"Node {index}: {result.stderr.strip()[:1500]}",
                           int(match.group(1)) if match else None)
        output = result.stdout.strip()
        try:
            return json.loads(output)
        except ValueError:
            return output

    def verify_node(self, index: int) -> dict:
        info = self.rpc(index, "getblockchaininfo")
        if info.get("chain") != self.chain:
            raise DevnetError(f"Node {index} is not {self.chain}; refusing to operate")
        rpcinfo = self.rpc(index, "getrpcinfo")
        expected = self.node(index) / self.chain / "debug.log"
        if Path(rpcinfo.get("logpath", "")).resolve() != expected:
            raise DevnetError(f"Node {index} is using an unexpected data directory")
        return info

    @staticmethod
    def port_free(port: int) -> bool:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as listener:
            # Match the daemon's listener semantics: old connections in TIME_WAIT
            # must not look like an active owner after a graceful restart.
            listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            try:
                listener.bind(("127.0.0.1", port))
            except OSError:
                return False
        return True

    def require_stopped(self) -> None:
        for index, entry in self.read_state().items():
            if self.owned(int(index), entry):
                raise DevnetError("Devnet already running. Stop it before this operation.")
            if self.pid_command(entry["pid"]):
                raise DevnetError("A recorded PID belongs to another process; refusing to act on it")
        for port in [self.p2p_base + i for i in range(NODE_COUNT)] + [self.rpc_base + i for i in range(NODE_COUNT)]:
            if not self.port_free(port):
                raise DevnetError(f"Port {port} is already in use; no existing process will be stopped")

    def start(self) -> None:
        self.setup()
        self.require_binaries()
        self.require_stopped()
        if shutil.disk_usage(self.root).free < 1024 ** 3:
            raise DevnetError("At least 1 GiB free disk space is required to run the devnet")
        state = {}
        children = []
        try:
            for index in range(NODE_COUNT):
                token = uuid.uuid4().hex
                node = self.node(index)
                log_path = node / "startup.log"
                fd = os.open(log_path, os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o600)
                with os.fdopen(fd, "ab") as output:
                    process = subprocess.Popen(
                        [str(self.binary), f"-{self.chain}", "-nosettings", f"-datadir={node}",
                         f"-conf={node / 'bitcoin.conf'}", "-daemon=0",
                         f"-uacomment={self.process_label}-{token}"],
                        stdin=subprocess.DEVNULL, stdout=output, stderr=subprocess.STDOUT,
                        start_new_session=True)
                children.append((index, process))
                state[str(index)] = {"pid": process.pid, "token": token}
                self.save_state(state)
            deadline = time.monotonic() + 45
            ready = set()
            while time.monotonic() < deadline:
                for index, process in children:
                    if process.poll() is not None:
                        raise DevnetError(f"Node {index} exited; inspect {self.node(index) / 'startup.log'}")
                    if index not in ready:
                        try:
                            self.verify_node(index)
                            ready.add(index)
                        except RpcError:
                            pass
                if len(ready) == NODE_COUNT:
                    self.wait_connected(state)
                    return
                time.sleep(0.25)
            raise DevnetError("Nodes did not become ready within 45 seconds")
        except BaseException:
            # These are direct children from this invocation; still check identity
            # before sending a signal. Never signal a PID read from disk alone.
            for index, process in children:
                if process.poll() is None and self.owned(index, state[str(index)]):
                    process.terminate()
                    try:
                        process.wait(timeout=15)
                    except subprocess.TimeoutExpired:
                        pass
            remaining = {key: value for key, value in state.items() if self.owned(int(key), value)}
            self.save_state(remaining)
            raise

    def status(self) -> list[dict]:
        self.setup()
        state = self.read_state()
        statuses = []
        for index in range(NODE_COUNT):
            entry = state.get(str(index))
            item = {"node": index, "p2p_port": self.p2p_base + index, "rpc_port": self.rpc_base + index}
            if entry and self.owned(index, entry):
                try:
                    info = self.verify_node(index)
                    item.update(status="running", height=info["blocks"], bestblockhash=info["bestblockhash"])
                except DevnetError as error:
                    item.update(status="unhealthy", detail=str(error))
            elif entry and self.pid_command(entry["pid"]):
                item["status"] = "ownership-mismatch"
            elif not self.port_free(self.rpc_base + index) or not self.port_free(self.p2p_base + index):
                item["status"] = "port-in-use-by-unowned-process"
            else:
                item["status"] = "stopped"
            statuses.append(item)
        return statuses

    def stop(self) -> None:
        self.setup()
        state = self.read_state()
        errors = []
        for key, entry in list(state.items()):
            index = int(key)
            if not self.owned(index, entry):
                if self.pid_command(entry["pid"]):
                    errors.append(f"Node {index}: PID ownership mismatch; left untouched")
                else:
                    state.pop(key)
                continue
            try:
                self.verify_node(index)
                self.rpc(index, "stop")
            except DevnetError as error:
                errors.append(str(error))
        deadline = time.monotonic() + 30
        while time.monotonic() < deadline:
            active = {key: entry for key, entry in state.items() if self.owned(int(key), entry)}
            if not active:
                break
            time.sleep(0.2)
        for key, entry in list(state.items()):
            if not self.pid_command(entry["pid"]):
                state.pop(key)
            elif self.owned(int(key), entry):
                errors.append(f"Node {key} has not exited; no force-kill was attempted")
        self.save_state(state)
        if errors:
            raise DevnetError("; ".join(errors))

    def wait_connected(self, state: dict, timeout: float = 40) -> None:
        """Require all three distinct owned peers and completed P2P handshakes.

        RPC readiness alone is insufficient: peers may still be connecting or
        retrying. As in upstream's connect_nodes test helper, a received pong
        proves that the handshake has progressed to normal message processing.
        """
        markers = {index: f"{self.process_label}-{state[str(index)]['token']}"
                   for index in range(NODE_COUNT)}
        deadline = time.monotonic() + timeout
        missing = {}
        while time.monotonic() < deadline:
            missing = {}
            for index in range(NODE_COUNT):
                self.rpc(index, "ping")
                peers = self.rpc(index, "getpeerinfo")
                found = set()
                for peer in peers:
                    if not peer.get("addr", "").startswith("127.0.0.1:"):
                        raise DevnetError(f"Node {index} has a non-loopback peer")
                    if peer.get("bytesrecv_per_msg", {}).get("pong", 0) < 29:
                        continue
                    matches = {other for other, marker in markers.items()
                               if other != index and marker in peer.get("subver", "")}
                    if not matches:
                        raise DevnetError(f"Node {index} has a handshaken peer not owned by this controller")
                    found.update(matches)
                missing[index] = sorted(set(range(NODE_COUNT)) - {index} - found)
            if not any(missing.values()):
                return
            time.sleep(0.2)
        raise DevnetError(f"Four-node peer mesh was not ready within {timeout:g} seconds; missing peers: {missing}")

    def wait_synced(self, expected: str | None = None) -> str:
        deadline = time.monotonic() + 40
        while time.monotonic() < deadline:
            hashes = [self.rpc(index, "getbestblockhash") for index in range(NODE_COUNT)]
            if len(set(hashes)) == 1 and (expected is None or hashes[0] == expected):
                return hashes[0]
            time.sleep(0.2)
        raise DevnetError(f"The four nodes did not agree on the expected chain tip {expected}; observed {hashes}")

    def prepare_wallet(self, index: int) -> None:
        if WALLET in self.rpc(index, "listwallets"):
            return
        existing = {item["name"] for item in self.rpc(index, "listwalletdir")["wallets"]}
        self.rpc(index, "loadwallet" if WALLET in existing else "createwallet", WALLET)

    @staticmethod
    def file_sha256(path: Path) -> str:
        digest = hashlib.sha256()
        with path.open("rb") as stream:
            for block in iter(lambda: stream.read(1024 * 1024), b""):
                digest.update(block)
        return digest.hexdigest()

    def record_smoke(self, report: dict) -> None:
        """Preserve this attempt and atomically update the latest-attempt pointer."""
        secure_directory(self.local)
        evidence = self.local / "evidence"
        secure_directory(evidence)
        contents = json.dumps(report, indent=2) + "\n"
        write_private(evidence / f"devnet-smoke-{report['attempt_id']}.json", contents)
        write_private(evidence / "devnet-smoke.json", contents)

    @staticmethod
    def error_summary(error: BaseException) -> dict:
        message = str(error)[:2000]
        message = re.sub(r"__cookie__:\S+", "[redacted cookie]", message)
        message = re.sub(r"(?i)(rpcpassword\s*[=:]\s*)\S+", r"\1[redacted]", message)
        return {"type": type(error).__name__, "message": message}

    def smoke(self) -> dict:
        began = datetime.now(timezone.utc)
        report = {"network": "bitcoin-regtest", "quantum_security": False,
                  "randomx": False, "upstream_commit": UPSTREAM_COMMIT, "checks": {},
                  "attempt_id": began.strftime("%Y%m%dT%H%M%S%fZ") + "-" + uuid.uuid4().hex[:8],
                  "started_at": began.isoformat(), "passed": False, "phase": "preflight",
                  "cleanup": {"attempted": False, "status": "not-started"}}
        # Write before preflight so an earlier successful run can never masquerade
        # as the latest result when this run fails or is interrupted.
        self.record_smoke(report)
        started = False
        start_attempted = False
        work_completed = False
        failure = None
        try:
            report["controller_sha256"] = self.file_sha256(Path(__file__))
            git = subprocess.run(["git", "-C", str(self.root), "rev-parse", "HEAD"],
                                 capture_output=True, text=True, check=False, timeout=30)
            report["checkout_commit"] = git.stdout.strip() if git.returncode == 0 else None
            diff = subprocess.run(["git", "-C", str(self.root), "diff", "--no-ext-diff", "--binary", "HEAD", "--"],
                                  capture_output=True, check=False, timeout=30)
            report["tracked_diff_sha256"] = hashlib.sha256(diff.stdout).hexdigest() if diff.returncode == 0 else None
            report["tracked_files_dirty"] = bool(diff.stdout) if diff.returncode == 0 else None
            self.setup()
            self.require_binaries()
            self.require_stopped()
            report["binary_sha256"] = self.file_sha256(self.binary)
            report["phase"] = "starting"
            self.record_smoke(report)
            start_attempted = True
            self.start()
            started = True
            report["phase"] = "network-checks"
            for index in range(NODE_COUNT):
                self.verify_node(index)
                self.prepare_wallet(index)
            report["checks"]["four_regtest_nodes"] = True
            report["checks"]["complete_peer_mesh"] = True
            self.wait_synced()
            mining_address = self.rpc(0, "getnewaddress", wallet=True)
            blocks = self.rpc(0, "generatetoaddress", 101, mining_address)
            self.wait_synced(blocks[-1])
            before = self.rpc(1, "getbalance", wallet=True)
            recipient = self.rpc(1, "getnewaddress", wallet=True)
            txid = self.rpc(0, "sendtoaddress", recipient, 1, wallet=True)
            deadline = time.monotonic() + 20
            while time.monotonic() < deadline:
                if all(txid in self.rpc(i, "getrawmempool") for i in range(NODE_COUNT)):
                    break
                time.sleep(0.2)
            else:
                raise DevnetError("Payment did not propagate to all four mempools")
            blocks = self.rpc(0, "generatetoaddress", 1, mining_address)
            tip = self.wait_synced(blocks[-1])
            transaction = self.rpc(1, "gettransaction", txid, wallet=True)
            after = self.rpc(1, "getbalance", wallet=True)
            if transaction["confirmations"] < 1 or round(after - before, 8) != 1:
                raise DevnetError("Recipient did not receive exactly one confirmed test coin")
            report["checks"]["payment_propagates_and_confirms"] = True
            # Exercise actual validation, not just wallet-side insufficient funds.
            invalid = self.rpc(0, "createrawtransaction",
                               [{"txid": "01" * 32, "vout": 0}], {recipient: 1})
            rejection = self.rpc(0, "testmempoolaccept", [invalid])[0]
            if rejection.get("allowed") is not False or "missing" not in rejection.get("reject-reason", ""):
                raise DevnetError(f"Unexpected invalid-spend result: {rejection}")
            try:
                self.rpc(0, "sendrawtransaction", invalid)
            except RpcError as error:
                if error.code != -25:
                    raise DevnetError(f"Expected missing-input rejection (-25), received {error.code}") from error
            else:
                raise DevnetError("Node unexpectedly accepted a transaction spending nonexistent coins")
            report["checks"]["nonexistent_input_rejected"] = True
            for index in range(NODE_COUNT):
                peers = self.rpc(index, "getpeerinfo")
                if not peers or any(not peer["addr"].startswith("127.0.0.1:") for peer in peers):
                    raise DevnetError("Expected only loopback peers")
            report["checks"]["loopback_peers_only"] = True
            report["phase"] = "restart-check"
            self.stop()
            started = False
            self.start()
            started = True
            self.wait_synced(tip)
            self.prepare_wallet(1)
            restored = self.rpc(1, "gettransaction", txid, wallet=True)
            if (restored["confirmations"] < 1
                    or self.rpc(1, "getbalance", wallet=True) != after):
                raise DevnetError("Wallet or chain state changed across the restart")
            report["checks"]["restart_preserves_chain_and_wallet"] = True
            report.update(payment_txid=txid, bestblockhash=tip)
            work_completed = True
        except BaseException as error:
            failure = error
            report["error"] = self.error_summary(error)
        finally:
            if started:
                report["cleanup"]["attempted"] = True
                try:
                    self.stop()
                except BaseException as error:
                    report["cleanup"]["error"] = self.error_summary(error)
                    if failure is None:
                        failure = error
                        report["error"] = self.error_summary(error)
            if start_attempted:
                try:
                    statuses = self.status()
                    stopped = all(item["status"] == "stopped" for item in statuses)
                    report["checks"]["owned_nodes_stopped"] = stopped
                    report["cleanup"].update(status="stopped" if stopped else "incomplete",
                                             nodes=statuses)
                    if not stopped and failure is None:
                        failure = DevnetError("Nodes were not all stopped after smoke test")
                        report["error"] = self.error_summary(failure)
                except BaseException as error:
                    report["cleanup"].update(status="unknown", error=self.error_summary(error))
                    if failure is None:
                        failure = error
                        report["error"] = self.error_summary(error)
            else:
                report["cleanup"]["status"] = "not-needed-no-network-started"
            report["passed"] = bool(work_completed and failure is None)
            report["finished_at"] = datetime.now(timezone.utc).isoformat()
            if report["passed"]:
                report["phase"] = "complete"
            self.record_smoke(report)
        if failure is not None:
            raise failure
        return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("setup", "start", "status", "stop", "smoke"))
    args = parser.parse_args()
    os.umask(0o077)
    controller = Devnet()
    try:
        # Serialize separate CLI invocations before reading or changing process
        # ownership state. Nonblocking acquisition gives a clear user error.
        secure_directory(controller.local)
        secure_directory(controller.data)
        reject_symlinks(controller.data)
        lock_path = controller.data / "controller.lock"
        flags = os.O_RDWR | os.O_CREAT | getattr(os, "O_NOFOLLOW", 0)
        with os.fdopen(os.open(lock_path, flags, 0o600), "r+") as lock:
            try:
                fcntl.flock(lock.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError as error:
                raise DevnetError("Another devnet command is in progress") from error
            result = getattr(controller, args.command)()
        print(json.dumps(result, indent=2) if result is not None else f"Devnet {args.command} complete.")
        return 0
    except (DevnetError, OSError, subprocess.TimeoutExpired) as error:
        print(f"Devnet error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
